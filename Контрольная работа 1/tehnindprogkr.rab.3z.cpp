#include <iostream>

using namespace std;

// Функция для вычисления значения по упрощенной формуле
// Исходное выражение из Варианта 3: 0.8 * (6x - 2) + 1.6 * (x - 4)
// Упрощение: 4.8x - 1.6 + 1.6x - 6.4 = 6.4x - 8.0
double calculate(double x) {
    // Возвращаем результат сразу в сокращенном виде по требованию задачи
    return 6.4 * x - 8.0;
}

int main() {
    // Переменная для хранения введенного коэффициента
    double x;

    // Ввод аргумента x с клавиатуры
    cout << "Введите x: ";
    cin >> x;

    // Вызов функции подсчета упрощенного выражения
    double result = calculate(x);

    // Вывод итогового результата в консоль
    cout << "Результат: " << result << endl;

    return 0;
}