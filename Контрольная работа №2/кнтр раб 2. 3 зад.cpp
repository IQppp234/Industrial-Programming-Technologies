#include <iostream>
using namespace std;

// Рекурсивная функция для перекладывания ингредиентов
void hanoi(int n, int from, int to, int aux) {
    if (n == 0) {
        return; // Базовый случай: перекладывать нечего
    }
    // Перекладываем n-1 ингредиентов на вспомогательную салфетку
    hanoi(n - 1, from, aux, to);
    
    // Перекладываем самый большой ингредиент на нужную салфетку
    cout << "Ingredient " << n << " move from " << from << " to " << to << endl;
    
    // Перекладываем n-1 ингредиентов со вспомогательной на нужную
    hanoi(n - 1, aux, to, from);
}

int main() {
    int n;
    cin >> n;
    // Вызываем функцию: перекладываем n ингредиентов с 1-й на 3-ю салфетку, используя 2-ю как вспомогательную
    hanoi(n, 1, 3, 2);
    return 0;
}